/**
 * Назви показників для інтерфейсу — єдине джерело істини.
 *
 * Наукова нотація (η, η_c, λ_c, Δη) лишається там, де вона справді потрібна:
 * у `docs/metrics.md`, у назвах полів API (`msr`, `msr_c`, `clr`) і в
 * заголовках XLSX/PDF — там її можна звірити з літературою. На екрані вона
 * нічого не пояснювала: жоден із користувачів не читає грецьку абетку як
 * «успішність», і ніде в інтерфейсі не було розшифровки.
 *
 * Тому в UI показуємо звичайну українську назву, а формулу і символ віддаємо
 * підказкою (`title`). Повний розбір — «Настанова користувача» §5
 * (`docs/passport/03-instrukciya-korystuvacha.md`).
 */

export interface MetricLabel {
  /** Повна назва — для заголовків карток і підписів під числом. */
  label: string;
  /** Коротка назва — для колонок таблиць, де місця мало. */
  short: string;
  /** Розшифровка з формулою — у `title`, спливає при наведенні. */
  hint: string;
}

